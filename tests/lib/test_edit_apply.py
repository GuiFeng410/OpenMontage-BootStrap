def test_apply_note_only_intent(project):
    ei.create_intent("demo-pro", _intent(actions=[], note="字幕换中文"))
    result = ea.apply_intent("demo-pro", "intent-t1")
    assert result["applied"] is True
    assert result["cut_count"] == {"before": 4, "after": 4}
