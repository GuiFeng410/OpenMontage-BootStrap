"""Tests for the Agent-side edit loop: digest, merge, drift, status."""

from __future__ import annotations

import json

import pytest

import lib.edit_apply as ea
import lib.edit_intents as ei


def _sample_cuts():
    return [
        {"id": "c01", "source": "assets/video/seg01.mp4", "in_seconds": 0.0, "out_seconds": 4.0},
        {"id": "c02", "source": "assets/video/seg02.mp4", "in_seconds": 1.2, "out_seconds": 6.5},
        {"id": "c03", "source": "assets/video/seg03.mp4", "in_seconds": 2.0, "out_seconds": 5.0},
        {"id": "c04", "source": "assets/video/seg04.mp4", "in_seconds": 0.5, "out_seconds": 3.2},
    ]


@pytest.fixture
def project(monkeypatch, tmp_path):
    root = tmp_path / "projects"
    p = root / "demo-pro"
    (p / "artifacts").mkdir(parents=True)
    (p / "intents").mkdir(parents=True)
    (p / "artifacts" / "edit_decisions.json").write_text(json.dumps({
        "version": "1.0",
        "render_runtime": "ffmpeg",
        "cuts": _sample_cuts(),
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    monkeypatch.setattr(ea, "PROJECTS_DIR", root)
    monkeypatch.setattr(ei, "PROJECTS_DIR", root)
    return p


def _intent(project_id="demo-pro", **overrides):
    data = {
        "version": "1.0",
        "intent_id": "intent-t1",
        "project_id": project_id,
        "created_at": "2026-08-12T00:00:00+00:00",
        "status": "pending",
        "base": {"artifact": "edit_decisions", "cuts_revision": ea.cuts_digest(_sample_cuts())},
        "actions": [{"type": "delete", "cut_id": "c03"}],
    }
    data.update(overrides)
    return data


# ---- digest cross-language consistency ------------------------------------

def test_digest_matches_board_generated_revision():
    # The revision string was generated by board-edit.js in the browser for the
    # exact same 4-cut sample (intent-1786448389352.json, base.cuts_revision).
    assert ea.cuts_digest(_sample_cuts()) == "h1gohvfo"


def test_digest_changes_when_cuts_change():
    cuts = _sample_cuts()
    base = ea.cuts_digest(cuts)
    cuts[0]["out_seconds"] = 5.0
    assert ea.cuts_digest(cuts) != base


# ---- apply / merge --------------------------------------------------------

def test_apply_delete(project):
    ei.create_intent("demo-pro", _intent(actions=[{"type": "delete", "cut_id": "c03"}]))
    result = ea.apply_intent("demo-pro", "intent-t1")
    assert result["applied"] is True
    cuts = ea.load_edit_decisions("demo-pro")["cuts"]
    assert [c["id"] for c in cuts] == ["c01", "c02", "c04"]
    assert result["removed_cuts"] == ["c03"]
    assert result["friendly_zh"]


def test_apply_trim_writes_reason(project):
    ei.create_intent("demo-pro", _intent(actions=[
        {"type": "trim", "cut_id": "c02", "in_seconds": 1.5, "out_seconds": 7.0},
    ]))
    ea.apply_intent("demo-pro", "intent-t1")
    c02 = next(c for c in ea.load_edit_decisions("demo-pro")["cuts"] if c["id"] == "c02")
    assert c02["in_seconds"] == 1.5
    assert c02["out_seconds"] == 7.0
    assert c02["reason"] == "user intent intent-t1"


def test_apply_reorder(project):
    ei.create_intent("demo-pro", _intent(actions=[
        {"type": "reorder", "order": ["c04", "c01", "c03", "c02"]},
    ]))
    ea.apply_intent("demo-pro", "intent-t1")
    ids = [c["id"] for c in ea.load_edit_decisions("demo-pro")["cuts"]]
    assert ids == ["c04", "c01", "c03", "c02"]


def test_apply_combined_like_user_submission(project):
    # Mirrors the real board submission: delete c03 + reorder [c02, c04, c01].
    ei.create_intent("demo-pro", _intent(actions=[
        {"type": "delete", "cut_id": "c03"},
        {"type": "reorder", "order": ["c02", "c04", "c01"]},
    ]))
    ea.apply_intent("demo-pro", "intent-t1")
    ids = [c["id"] for c in ea.load_edit_decisions("demo-pro")["cuts"]]
    assert ids == ["c02", "c04", "c01"]


