def test_plan_text_lists_actions():
    text = ea.plan_text(_intent(actions=[
        {"type": "trim", "cut_id": "c01", "in_seconds": 0.0, "out_seconds": 3.0},
        {"type": "delete", "cut_id": "c03"},
        {"type": "reorder", "order": ["c02", "c01", "c04"]},
        {"type": "delete", "cut_id": "c99", "note": "这段不要了"},
    ]))
    assert "c01 时长改为 0.0–3.0 秒" in text
    assert "删除片段 c03" in text
    assert "调整片段顺序" in text
    assert "这段不要了" in text


def test_list_pending_filters_status(project):
    ei.create_intent("demo-pro", _intent(intent_id="a", status="pending"))
    ei.create_intent("demo-pro", _intent(intent_id="b", status="confirmed"))
    ids = [i["intent_id"] for i in ea.list_pending("demo-pro")]
    assert ids == ["a"]


