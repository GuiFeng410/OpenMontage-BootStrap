# ---- drift ----------------------------------------------------------------

def test_drift_marks_superseded_and_does_not_apply(project):
    ei.create_intent("demo-pro", _intent())
    # Change the cuts on disk after the intent was created.
    data = ea.load_edit_decisions("demo-pro")
    data["cuts"][0]["out_seconds"] = 6.0
    ea.save_edit_decisions("demo-pro", data)

    result = ea.apply_intent("demo-pro", "intent-t1")
    assert result["applied"] is False
    assert result["reason"] == "drift"
    assert "旧版本" in result["friendly_zh"]
    assert ei.get_intent("demo-pro", "intent-t1")["status"] == "superseded"
    # cuts untouched
    assert ea.load_edit_decisions("demo-pro")["cuts"][0]["out_seconds"] == 6.0


